import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const terraformVersion = "1.14.9";
const guid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function validateMetadata(metadata) {
  if (!metadata || metadata.schema !== 1 ||
      !/^[a-zA-Z0-9_.-]+\/[a-zA-Z0-9_.-]+$/.test(metadata.repository ?? "") ||
      !/^[0-9]+$/.test(metadata.runId ?? "") ||
      !/^[0-9]+$/.test(metadata.runAttempt ?? "") ||
      !/^[a-f0-9]{40}$/.test(metadata.commit ?? "") ||
      !/^[a-f0-9]{64}$/.test(metadata.sha256 ?? "") ||
      !["sales", "operations"].includes(metadata.team) ||
      !guid.test(metadata.subscriptionId ?? "") || !guid.test(metadata.tenantId ?? "") ||
      !/^[a-z0-9]{3,24}$/.test(metadata.stateAccount ?? "") ||
      metadata.terraformVersion !== terraformVersion) {
    throw new Error("Invalid saved-plan metadata.");
  }
}

export function verifyArtifact(metadata, actual) {
  validateMetadata(metadata);
  for (const key of ["repository", "team", "sha256", "commit", "terraformVersion", "subscriptionId", "tenantId", "stateAccount"]) {
    if (metadata[key] !== actual[key]) throw new Error(`Saved plan mismatch: ${key}.`);
  }
  const run = actual.run;
  if (!run || String(run.id) !== metadata.runId || String(run.run_attempt) !== metadata.runAttempt ||
      run.head_sha !== metadata.commit || run.head_branch !== "main" ||
      run.event !== "workflow_dispatch" || run.path !== ".github/workflows/plan.yml" ||
      run.status !== "completed" || run.conclusion !== "success") {
    throw new Error("Expected the successful main-branch plan workflow run and attempt.");
  }
  return metadata;
}

function command(program, args) {
  return execFileSync(program, args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

function main() {
  const [mode, directory, team, repository] = process.argv.slice(2);
  if (!["write", "check"].includes(mode) || !directory || !team || !repository) {
    throw new Error("Usage: node scripts/plan-artifact.mjs write|check DIRECTORY TEAM OWNER/REPO");
  }
  const metadataPath = resolve(directory, "plan-metadata.json");
  const sha256 = createHash("sha256").update(readFileSync(resolve(directory, "workload.tfplan"))).digest("hex");
  if (mode === "write") {
    if (process.env.GITHUB_ACTIONS !== "true" || process.env.GITHUB_REPOSITORY !== repository ||
        process.env.GITHUB_REF !== "refs/heads/main") {
      throw new Error("Metadata must be generated by the main-branch GitHub workflow.");
    }
    const metadata = {
      schema: 1, repository, team, sha256, terraformVersion,
      runId: process.env.GITHUB_RUN_ID, runAttempt: process.env.GITHUB_RUN_ATTEMPT,
      commit: process.env.GITHUB_SHA, subscriptionId: process.env.ARM_SUBSCRIPTION_ID,
      tenantId: process.env.ARM_TENANT_ID, stateAccount: process.env.STATE_ACCOUNT
    };
    validateMetadata(metadata);
    writeFileSync(metadataPath, `${JSON.stringify(metadata, null, 2)}\n`, { flag: "wx" });
    console.log("PASS: saved-plan checksum and run metadata written; no deployment performed.");
    return;
  }
  const metadata = JSON.parse(readFileSync(metadataPath, "utf8"));
  validateMetadata(metadata);
  if (metadata.repository !== repository) throw new Error("Saved plan belongs to a different repository.");
  if (command("git", ["status", "--porcelain", "--untracked-files=no"])) {
    throw new Error("Use a clean checkout: tracked files differ from the run commit.");
  }
  const run = JSON.parse(command("gh", ["api", `repos/${repository}/actions/runs/${metadata.runId}`]));
  const account = JSON.parse(command("az", ["account", "show", "--output", "json"]));
  const operator = command("az", ["ad", "signed-in-user", "show", "--query", "id", "--output", "tsv"]);
  if (!process.env.OPERATOR_OBJECT_ID || operator.toLowerCase() !== process.env.OPERATOR_OBJECT_ID.toLowerCase() ||
      account.user?.type !== "user") {
    throw new Error("Select the approved human operator login and set OPERATOR_OBJECT_ID.");
  }
  verifyArtifact(metadata, {
    repository, team, sha256, run, commit: command("git", ["rev-parse", "HEAD"]),
    terraformVersion: JSON.parse(command("terraform", ["version", "-json"])).terraform_version,
    subscriptionId: account.id, tenantId: account.tenantId, stateAccount: process.env.STATE_ACCOUNT
  });
  console.log(`PASS: ${team}, commit ${metadata.commit}, run ${metadata.runId}/${metadata.runAttempt}, SHA256 ${sha256}. Review the plan before any manual apply.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    main();
  } catch (error) {
    console.error(`ERROR: ${error.message}`);
    process.exitCode = 1;
  }
}
