// Regenerates Terraform import blocks for bootstrap resources that already exist in Azure,
// so a lost local state never turns into a "create again" (or worse, replace) plan.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const az = args => execFileSync("az", [...args, "-o", "tsv"], { encoding: "utf8" }).trim();
const [stateAccount, out = "infra/bootstrap/imports.generated.tf"] = process.argv.slice(2);
try {
  if (!/^[a-z0-9]{3,24}$/.test(stateAccount ?? "")) {
    throw new Error("Usage: node scripts/bootstrap-imports.mjs <state-storage-account> [output.tf]");
  }
  const lab = "wpc-2026";
  const sub = az(["account", "show", "--query", "id"]);
  const rg = `/subscriptions/${sub}/resourceGroups/${lab}`;
  const identity = `${rg}/providers/Microsoft.ManagedIdentity/userAssignedIdentities/wpc-2026-plan`;
  const account = `${rg}/providers/Microsoft.Storage/storageAccounts/${stateAccount}`;
  const principal = az(["identity", "show", "--ids", identity, "--query", "principalId"]);
  const reader = az(["role", "assignment", "list", "--scope", rg, "--assignee-object-id", principal,
    "--role", "Reader", "--query", `[?scope=='${rg}'].id | [0]`]);
  const imports = {
    "azurerm_storage_account.state": account,
    "azurerm_storage_container.state": `${account}/blobServices/default/containers/tfstate`,
    "azurerm_user_assigned_identity.plan": identity,
    "azurerm_federated_identity_credential.plan": `${identity}/federatedIdentityCredentials/github-plan`,
    "azurerm_role_assignment.plan_read": reader,
    "azurerm_resource_group_policy_assignment.private_workloads":
      `${rg}/providers/Microsoft.Authorization/policyAssignments/wpc-private-storage`
  };
  for (const [address, id] of Object.entries(imports)) {
    if (!id.startsWith(`/subscriptions/${sub}/resourceGroups/${lab}/`)) {
      throw new Error(`${address}: expected an existing resource inside ${lab}, got ${JSON.stringify(id)}.`);
    }
  }
  const body = Object.entries(imports)
    .map(([to, id]) => `import {\n  to = ${to}\n  id = "${id}"\n}\n`).join("\n");
  writeFileSync(out, `# Generated by scripts/bootstrap-imports.mjs. Local only, not committed.\n\n${body}`);
  console.log(`PASS: ${Object.keys(imports).length} import blocks written to ${out}. Review them with terraform plan before any apply.`);
} catch (error) {
  console.error(`ERROR: ${error.message}`);
  process.exitCode = 1;
}
